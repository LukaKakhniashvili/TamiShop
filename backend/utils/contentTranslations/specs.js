// ერთეულები — „რიცხვი + ერთეული" (1.2 კგ, 30 სმ, 100 მლ...)
const UNITS = [
  ['გ/მ²', 'g/m²', 'г/м²'],
  ['სმ²', 'cm²', 'см²'],
  ['კგ', 'kg', 'кг'],
  ['სმ', 'cm', 'см'],
  ['მმ', 'mm', 'мм'],
  ['მლ', 'ml', 'мл'],
  ['ლ', 'L', 'л'],
  ['მ', 'm', 'м'],
  ['გ', 'g', 'г'],
];
const GEO = '\\u10D0-\\u10FF';

const ruPlural = (n, one, few, many) => {
  const r = new Intl.PluralRules('ru').select(n);
  return r === 'one' ? one : r === 'few' ? few : many;
};

const RULES = [
  // 20 სთ-მდე → up to 20 h
  [/^(\d+(?:\.\d+)?) სთ-მდე$/, (m, l) => (l === 'en' ? `up to ${m[1]} h` : `до ${m[1]} ч`)],
  // 2 წელი → 2 years
  [/^(\d+) წელი$/, (m, l) => (l === 'en' ? `${m[1]} year${m[1] === '1' ? '' : 's'}` : `${m[1]} ${ruPlural(Number(m[1]), 'год', 'года', 'лет')}`)],
  // მარაგი: 12 ცალი
  [/^(\d+) ცალი$/, (m, l) => (l === 'en' ? `${m[1]} pcs` : `${m[1]} шт.`)],
  // რეიტინგი: 4.5 / 5 (146 შეფასება)
  [
    /^(\d+(?:\.\d+)?) \/ 5 \((\d+) შეფასება\)$/,
    (m, l) =>
      l === 'en'
        ? `${m[1]} / 5 (${m[2]} review${m[2] === '1' ? '' : 's'})`
        : `${m[1]} / 5 (${m[2]} ${ruPlural(Number(m[2]), 'отзыв', 'отзыва', 'отзывов')})`,
  ],
];

/** ქართული მნიშვნელობა → ენაზე; null — თუ ვერ ითარგმნა (ლექსიკონი უნდა შეივსოს) */
const translateValue = (value, lng) => {
  if (typeof value !== 'string') return value;
  if (!/[ა-ჿ]/.test(value)) return value; // ტექნიკური/ენისგან დამოუკიდებელი მნიშვნელობა
  if (VALUES[value]) return VALUES[value][lng];
  for (const [re, fn] of RULES) {
    const m = value.match(re);
    if (m) return fn(m, lng);
  }
  // მხოლოდ რიცხვები და ერთეულები (მაგ. „30 × 22 × 13 სმ", „35 მლ, 50 მლ, 100 მლ")
  let out = value;
  for (const [ka, en, ru] of UNITS) {
    out = out.replace(new RegExp(`(\\d)\\s?${ka}(?![${GEO}])`, 'g'), `$1 ${lng === 'en' ? en : ru}`);
  }
  return /[ა-ჿ]/.test(out) ? null : out;
};

const translateKey = (key, lng) => (/[ა-ჿ]/.test(key) ? KEYS[key]?.[lng] || null : key);

module.exports = { KEYS, VALUES, translateValue, translateKey };
